/*
    Write a program which accept number form user an display its factors in Decreasing order.
*/

#include<stdio.h>
#include<stdlib.h>

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///
///   Function Name           :FactRev
///   Input                   :Integer
///   Output                  :none(display result)
///   Description             :Display factors in reverse order
///   Date                    :07/11/2026
///   Author                  :Anand Rashtrapal Ingle
///
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void FactRev(int iNo)
{
    int iCnt = 0;
    for(iCnt = iNo/2; iCnt >=1; iCnt--)
    {
        if((iNo % iCnt) == 0)
        {
            printf("%d\t" , iCnt);
        }
    }
}

int main()
{
    int iValue = 0;

    printf("Enter number : \n");
    if((scanf("%d" , &iValue) != 1))
    {
        printf("Invalid input.\n");
    }

    FactRev(iValue);

    return EXIT_SUCCESS;
}


void Number(int iNo)
{
    if(iNo < 0)
    {
        iNo = -iNo;
    }

    if (iNo < 50)
    {
        printf("Small\n");
    } 
    else if (iNo >= 50 && iNo <= 100)
    {
        printf("Medium\n");
    }
    else
    {
        printf("Large\n");
    }
}
int main()
{
    int iValue = 0;
    printf("Enter number: \n");
    if(scanf("%d", &iValue) != 1) /*scanf chi return value equal to 1 nasel condition true if chya at ya*/
    {
        printf("inValid Input");
    }

    Number(iValue);

    return EXIT_SUCCESS;
}




void Table(int iNo)
{
    int iCnt = 0;
    int Table = 1;

    for(iCnt = 10; iCnt >= 1; iCnt--)
    {
        Table = iNo * iCnt;
        printf("%d\t" , Table);
    }
}

int main()
{ 
    int iValue = 0;
    printf("Enter number:\n");
    scanf("%d" , &iValue);

    Table(iValue);

    return EXIT_SUCCESS;
}



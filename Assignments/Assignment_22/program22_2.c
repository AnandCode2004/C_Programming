#include<stdio.h>
#include<stdlib.h>

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//     Function name:   Pattern
//     Input        :   Integer,Integer
//     Ouput        :   (None display symbols and numbers)
//     Description  :   Display pattern
//     Date         :   13/11/2026
//     Author       :   Anand Rashtrapal Ingle
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void Pattern(int iNo)
{   
    int iCnt = 0;
    for(iCnt = iNo; iCnt >= 1; iCnt--)
    {
        printf("%d\t#\t" , iCnt);
    }
  
}

int main()
{
    int ivalue = 0;

    printf("Enter number of elements : \n");
    scanf("%d" , &ivalue);

    Pattern(ivalue);

    return EXIT_SUCCESS;
}


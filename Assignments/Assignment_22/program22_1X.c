/*
    Accept number from user and display below pattern..
*/

#include<stdio.h>
#include<stdlib.h>


///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//     Function name:   Pattern
//     Input        :   Integer,Integer
//     Ouput        :   (None display characters in Reverse)
//     Description  :   Display pattern
//     Date         :   13/11/2026
//     Author       :   Anand Rashtrapal Ingle
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void Pattern(int iNo)
{
    int iCnt = 0;
    char ch = '\0';

    for(iCnt = 1 , ch = 'A' + iNo-1; iCnt <= iNo; iCnt++ , ch--)
    {
        printf("%c\t" , ch);
    }
    printf("\n\n");
    
}

int main()
{
    int iValue1 = 0;

    printf("Enter number of elements : \n");
    scanf("%d" , &iValue1);

    Pattern(iValue1);

    return EXIT_SUCCESS;
}


/*  Accept a number from the user and display the first N Odd numbers. */

#include<stdio.h>
#include<stdlib.h>

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//     Function name:   Pattern
//     Input        :   Integer,Integer
//     Output       :   (Display Odd numbers)
//     Description  :   Display pattern
//     Date         :   13/11/2026
//     Author       :   Anand Rashtrapal Ingle
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void Pattern(int iNo)
{   
    int iCnt = 0;
    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {
        printf("%d\t" , iCnt * 2-1);
    }
  
}

int main()
{
    int ivalue = 0;

    printf("Enter number of elements : \n");
    scanf("%d" , &ivalue);

    Pattern(ivalue);

    return EXIT_SUCCESS;
}



/*  Accept a number from the user and display the first N even numbers. */

#include<stdio.h>
#include<stdlib.h>

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//     Function name:   Pattern
//     Input        :   Integer,Integer
//     Ouput        :   (Display even numbers)
//     Description  :   Display pattern
//     Date         :   13/11/2026
//     Author       :   Anand Rashtrapal Ingle
//
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void Pattern(int iNo)
{   
    int iCnt = 0;
    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {
        printf("%d\t" , iCnt * 2);
    }
  
}

int main()
{
    int ivalue = 0;

    printf("Enter number of elements : \n");
    scanf("%d" , &ivalue);

    Pattern(ivalue);

    return EXIT_SUCCESS;
}

